#!/usr/bin/env python3
"""
Environment Setup Script for Certificate Verification System
Helps users configure their .env file with proper values
"""

import os
import shutil
from pathlib import Path

def setup_environment():
    """Setup environment configuration"""
    print("🔧 Certificate Verification System - Environment Setup")
    print("=" * 60)
    
    # Check if .env already exists
    if os.path.exists('.env'):
        print("✅ .env file already exists.")
        response = input("Do you want to update it? (y/N): ").strip().lower()
        if response != 'y':
            print("Setup cancelled.")
            return
        print()
    
    # Copy .env.example to .env if it doesn't exist
    if not os.path.exists('.env'):
        if os.path.exists('.env.example'):
            shutil.copy('.env.example', '.env')
            print("✅ Created .env file from .env.example")
        else:
            print("❌ .env.example file not found!")
            return
    
    print("\n📝 Please provide the following configuration values:")
    print("(Press Enter to keep existing/default values)\n")
    
    # Configuration prompts
    configs = []
    
    # MongoDB
    print("🗄️ Database Configuration:")
    mongodb_uri = input("MongoDB URI: ").strip()
    if mongodb_uri:
        configs.append(('MONGODB_URI', mongodb_uri))
    
    # AI Configuration
    print("\n🤖 AI Configuration:")
    gemini_key = input("Google Gemini API Key: ").strip()
    if gemini_key:
        configs.append(('GEMINI_API_KEY', gemini_key))
    
    tesseract_path = input("Tesseract OCR Path (Windows: C:\\Program Files\\Tesseract-OCR\\tesseract.exe): ").strip()
    if tesseract_path:
        configs.append(('TESSERACT_PATH', tesseract_path))
    
    python_exec = input("Python Executable (python/python3): ").strip()
    if python_exec:
        configs.append(('PYTHON_EXECUTABLE', python_exec))
    
    # Thresholds
    print("\n⚖️ AI Thresholds (0.0 - 1.0):")
    fraud_threshold = input("Fraud Detection Threshold (default: 0.7): ").strip()
    if fraud_threshold:
        try:
            float(fraud_threshold)
            configs.append(('FRAUD_THRESHOLD', fraud_threshold))
        except ValueError:
            print("⚠️ Invalid fraud threshold, using default")
    
    signature_threshold = input("Signature Verification Threshold (default: 0.5): ").strip()
    if signature_threshold:
        try:
            float(signature_threshold)
            configs.append(('SIGNATURE_THRESHOLD', signature_threshold))
        except ValueError:
            print("⚠️ Invalid signature threshold, using default")
    
    # Server Configuration
    print("\n🌐 Server Configuration:")
    port = input("Backend Port (default: 5000): ").strip()
    if port:
        configs.append(('PORT', port))
    
    frontend_url = input("Frontend URL (default: http://localhost:3000): ").strip()
    if frontend_url:
        configs.append(('FRONTEND_URL', frontend_url))
    
    blockchain_url = input("Blockchain URL (default: http://localhost:8545): ").strip()
    if blockchain_url:
        configs.append(('BLOCKCHAIN_URL', blockchain_url))
    
    # Update .env file
    if configs:
        print(f"\n📝 Updating .env file with {len(configs)} new values...")
        update_env_file(configs)
        print("✅ Environment configuration updated!")
    else:
        print("\n📝 No changes made to .env file.")
    
    print("\n🎯 Next Steps:")
    print("1. Review your .env file and make sure all values are correct")
    print("2. Install dependencies: npm install (in both root and backend)")
    print("3. Install Python dependencies: pip install -r backend/requirements.txt")
    print("4. Start the system: npm run dev")
    print("5. Run integration tests: python test_integrated_system_with_env.py")

def update_env_file(configs):
    """Update .env file with new configuration values"""
    # Read existing .env file
    env_lines = []
    if os.path.exists('.env'):
        with open('.env', 'r') as f:
            env_lines = f.readlines()
    
    # Create a dictionary of existing values
    existing_config = {}
    for line in env_lines:
        line = line.strip()
        if line and not line.startswith('#') and '=' in line:
            key, value = line.split('=', 1)
            existing_config[key.strip()] = value.strip()
    
    # Update with new values
    for key, value in configs:
        existing_config[key] = value
    
    # Write updated .env file
    with open('.env', 'w') as f:
        f.write("# Certificate Verification System - Environment Configuration\n")
        f.write("# Generated by setup script\n\n")
        
        # Group configurations
        groups = {
            "Database Configuration": ["MONGODB_URI"],
            "AI Configuration": ["GEMINI_API_KEY", "TESSERACT_PATH", "PYTHON_EXECUTABLE"],
            "File Upload Configuration": ["MAX_FILE_SIZE", "ALLOWED_EXTENSIONS", "UPLOAD_PATH", "TEMP_PATH"],
            "AI Thresholds": ["FRAUD_THRESHOLD", "SIGNATURE_THRESHOLD", "OCR_CONFIDENCE_THRESHOLD"],
            "Server Configuration": ["PORT", "FRONTEND_URL", "BLOCKCHAIN_URL", "HARDHAT_NETWORK"],
            "Blockchain Configuration": ["GAS_LIMIT", "GAS_PRICE"],
            "Security Configuration": ["JWT_SECRET", "SESSION_SECRET"],
            "Development Configuration": ["NODE_ENV", "LOG_LEVEL"]
        }
        
        for group_name, group_keys in groups.items():
            f.write(f"# {group_name}\n")
            for key in group_keys:
                if key in existing_config:
                    f.write(f"{key}={existing_config[key]}\n")
            f.write("\n")

def validate_environment():
    """Validate current environment configuration"""
    print("🔍 Validating Environment Configuration...")
    
    required_vars = [
        'MONGODB_URI',
        'GEMINI_API_KEY',
        'TESSERACT_PATH',
        'PYTHON_EXECUTABLE'
    ]
    
    missing = []
    invalid = []
    
    for var in required_vars:
        value = os.getenv(var)
        if not value or value == 'your-' + var.lower().replace('_', '-') + '-here':
            missing.append(var)
    
    # Check if paths exist
    tesseract_path = os.getenv('TESSERACT_PATH')
    if tesseract_path and not os.path.exists(tesseract_path):
        invalid.append(f"TESSERACT_PATH: {tesseract_path} (file not found)")
    
    # Check thresholds
    for threshold_var in ['FRAUD_THRESHOLD', 'SIGNATURE_THRESHOLD']:
        value = os.getenv(threshold_var)
        if value:
            try:
                threshold = float(value)
                if not 0.0 <= threshold <= 1.0:
                    invalid.append(f"{threshold_var}: {value} (should be between 0.0 and 1.0)")
            except ValueError:
                invalid.append(f"{threshold_var}: {value} (not a valid number)")
    
    if missing:
        print(f"❌ Missing required variables: {', '.join(missing)}")
    
    if invalid:
        print(f"⚠️ Invalid configurations: {', '.join(invalid)}")
    
    if not missing and not invalid:
        print("✅ Environment configuration looks good!")
        return True
    
    return False

def main():
    """Main function"""
    if len(os.sys.argv) > 1 and os.sys.argv[1] == 'validate':
        from dotenv import load_dotenv
        load_dotenv()
        validate_environment()
    else:
        setup_environment()

if __name__ == "__main__":
    main()
